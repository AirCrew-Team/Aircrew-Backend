// Búsqueda sin distinguir mayúsculas. Map: «constructor» no encuentra nada heredado.
const citiesByLowerCase = new Map(US_CITIES.map((city) => [city.toLowerCase(), city]));

// Devuelve la ciudad con la forma del catálogo, o null si no está.
function findUsCity(value) {
  if (typeof value !== 'string') return null;
  return citiesByLowerCase.get(value.trim().toLowerCase()) || null;
}

module.exports = { US_CITIES, findUsCity };
